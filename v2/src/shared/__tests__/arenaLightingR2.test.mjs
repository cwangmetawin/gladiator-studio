import test from 'node:test';
import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine.js';
import { createLoader } from './loadTs.mjs';

const { load } = createLoader();
const luminance = rgb => rgb[0] * 0.2126 + rgb[1] * 0.7152 + rgb[2] * 0.0722;

test('the landed sand is lit between engravings, with brighter rims and spatial light falloff', async () => {
  const { sampleArenaFloor } = await load('features/arena/arenaLighting.ts');
  const sand = [];
  for (let z = -10; z <= 10; z += 2) for (let x = -10; x <= 10; x += 2) {
    if (Math.hypot(x + 0.37, z + 0.23) < 11) sand.push(sampleArenaFloor(x + 0.37, z + 0.23));
  }
  assert.ok(sand.every(rgb => rgb.every(value => Number.isFinite(value) && value >= 0)));
  assert.ok(sand.reduce((sum, rgb) => sum + luminance(rgb), 0) / sand.length > 0.12,
    'sand remains visible where no bright line crosses it');
  assert.ok(luminance(sampleArenaFloor(12, 0)) > 0.7, 'the sand rim has an emissive core');
  assert.ok(luminance(sampleArenaFloor(-4.37, 3.23)) > luminance(sampleArenaFloor(8.37, -7.23)),
    'overhead light gives the floor a direction and depth');
  assert.ok(luminance(sampleArenaFloor(35, 0)) < 0.001, 'the floor feathers away outside the arena');
});

test('actual arena outlines have screen-space glow geometry on the supplied engine and warm with the existing world meshes', async () => {
  const B = await load('shared/babylon/babylonCore.ts');
  const A = await load('features/arena/arenaCore.ts');
  const { createArenaWorld } = await load('features/arena/arenaWorld.ts');
  const engine = new NullEngine();
  try {
    const scene = new B.Scene(engine), camera = new A.FreeCamera('lighting-test', new B.Vector3(0, 0, 20), scene);
    const world = createArenaWorld(B, A, scene, false);
    const outline = scene.getMeshByName('arenaColosseum');
    assert.equal(outline.material.getClassName(), 'ShaderMaterial', 'the glow is generated by the real outline material');
    assert.ok(outline.isVerticesDataPresent('uv'), 'each ribbon has a cross-section for the halo');
    assert.ok(outline.isVerticesDataPresent('normal'), 'each ribbon stores its path tangent');
    assert.ok(world.meshes.some(mesh => mesh === outline), 'the outline shader is in the existing scene warmup set');
    assert.equal(outline.material.alphaMode, B.Constants.ALPHA_ADD);
    assert.equal(scene.textures.length, 1, 'lighting adds no texture beside the existing one-pixel sky');
    const count = outline.getTotalVertices();
    world.update({ fade: 1, night: 1, time: 0, camera });
    world.update({ fade: 1, night: 1, time: 1, camera });
    assert.equal(outline.getTotalVertices(), count, 'frame updates only touch existing uniforms');
    world.dispose();
    assert.equal(scene.materials.filter(material => material.name.startsWith('arena')).length, 0,
      'world-owned materials are released; Babylon owns its lazily created default material');
    assert.equal(scene.textures.length, 0);
    scene.dispose();
  } finally { engine.dispose(); }
});

test('portal lettering is baked from Saira Title and the wider lit jambs rise above the former frame', async () => {
  const { SAIRA_TITLE_GLYPHS } = await load('features/arena/sairaGateGlyphs.ts');
  const { createPageGates } = await load('features/arena/pageGates.ts');
  const { pageGateGeometry } = await load('features/arena/pageGateMeshes.ts');
  assert.ok(SAIRA_TITLE_GLYPHS.A.length > 20, 'A retains the font outline and counter');
  for (const gate of createPageGates(64)) {
    const data = pageGateGeometry(gate, false), tangent = [-gate.outward[2], gate.outward[0]];
    let width = 0, litHighJamb = false, hdr = false;
    for (let vertex = 0; vertex < data.positions.length / 3; vertex++) {
      const dx = data.positions[vertex * 3] - gate.center[0], z = data.positions[vertex * 3 + 2] - gate.center[2];
      const x = dx * tangent[0] + z * tangent[1], height = data.positions[vertex * 3 + 1] - gate.floorY;
      width = Math.max(width, Math.abs(x) * 2);
      if (Math.abs(x) > 1 && height > 2.8 && height < 3.1) litHighJamb = true;
      if (Math.max(...data.colors.slice(vertex * 4, vertex * 4 + 3)) > 1.1) hdr = true;
    }
    assert.ok(width >= 3.2, `${gate.id} has a broad architectural surround`);
    assert.ok(litHighJamb, `${gate.id} opening is visibly taller`);
    assert.ok(hdr, `${gate.id} trim carries light above the flat steel face`);
  }
});
