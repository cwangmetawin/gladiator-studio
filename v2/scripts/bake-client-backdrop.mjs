// Projects the homepage arena through its final camera. No browser, canvas or Babylon runtime.
//   node scripts/bake-client-backdrop.mjs
//   node scripts/bake-client-backdrop.mjs --check
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

export const WIDTH = 1920;
export const HEIGHT = 1080;
const OUTPUT = fileURLToPath(new URL('../public/arena/client-backdrop.svg', import.meta.url));
let recipe;

function arenaRecipe() {
  recipe ??= build({
    stdin: { contents: `
      export { colosseumLines } from '../src/features/arena/colosseumGeometry';
      export { createCameraTrack } from '../src/features/arena/cameraTrack';
      export { JOURNEY_SCREENS } from '../src/features/arena/journeyProgress';
    `, resolveDir: dirname(fileURLToPath(import.meta.url)), loader: 'ts' },
    bundle: true, write: false, format: 'esm', platform: 'node', logLevel: 'error',
  }).then(result => import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`));
  return recipe;
}

export async function finalCamera(frame = { distance: 9, offsetX: 0, offsetY: 0.8, fov: 0.62, mouthY: -0.75 }) {
  const { createCameraTrack, JOURNEY_SCREENS } = await arenaRecipe();
  return createCameraTrack(frame)(JOURNEY_SCREENS);
}

/** Clip each segment in camera space before division, including lines crossing behind the eye. */
export function projectSegment(start, end, camera, width = WIDTH, height = HEIGHT) {
  const cos = Math.cos(camera.pitch), sin = Math.sin(camera.pitch);
  const view = ([x, y, z]) => [x - camera.x, (y - camera.y) * cos + (z - camera.z) * sin,
    -(y - camera.y) * sin + (z - camera.z) * cos];
  const a = view(start), b = view(end), tanV = Math.tan(camera.fov / 2), tanH = tanV * width / height;
  const planes = [p => p[2] - 0.1, p => p[0] + p[2] * tanH, p => p[2] * tanH - p[0],
    p => p[1] + p[2] * tanV, p => p[2] * tanV - p[1]];
  let from = 0, to = 1;
  for (const plane of planes) {
    const d0 = plane(a), d1 = plane(b);
    if (d0 < 0 && d1 < 0) return null;
    if (d0 < 0) from = Math.max(from, d0 / (d0 - d1));
    if (d1 < 0) to = Math.min(to, d0 / (d0 - d1));
    if (from > to) return null;
  }
  return [from, to].map(t => {
    const [x, y, z] = a.map((value, i) => value + (b[i] - value) * t);
    return [Math.max(0, Math.min(width, width / 2 * (1 + x / (z * tanH)))),
      Math.max(0, Math.min(height, height / 2 * (1 - y / (z * tanV))))];
  });
}

const pair = point => point.map(value => Number(value.toFixed(1))).join(' ');

function linePath(line, camera) {
  let path = '', previous = null;
  for (let i = 1; i < line.points.length; i++) {
    const segment = projectSegment(line.points[i - 1], line.points[i], camera);
    if (!segment) { previous = null; continue; }
    const [a, b] = segment.map(pair);
    if (a === b) continue;
    path += a === previous ? `L${b}` : `M${a}L${b}`;
    previous = b;
  }
  return path;
}

export async function bakeBackdrop() {
  const { colosseumLines } = await arenaRecipe(), camera = await finalCamera();
  const groups = new Map();
  for (const line of colosseumLines(64)) {
    const path = linePath(line, camera);
    if (!path) continue;
    const opacity = Math.min(0.9, line.alpha * line.gain * 0.85).toFixed(2);
    const key = `${line.kind}:${opacity}`;
    const group = groups.get(key) ?? { opacity, paths: [] };
    group.paths.push(path); groups.set(key, group);
  }
  const paths = [...groups.values()].map(group =>
    `  <path opacity="${group.opacity}" d="${group.paths.join('')}"/>`).join('\n');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" fill="none" stroke="#7fb3d6" stroke-width="1.4">
  <!-- Generated by bake-client-backdrop.mjs from colosseumGeometry and cameraTrack at the journey end. -->
${paths}
</svg>\n`;
}

function argumentsFor(args) {
  let check = false, output = OUTPUT;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--check') check = true;
    else if (args[i] === '--output' && args[i + 1] && !args[i + 1].startsWith('--')) output = resolve(args[++i]);
    else throw new Error(`Unknown or incomplete argument: ${args[i]}`);
  }
  return { check, output };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { check, output } = argumentsFor(process.argv.slice(2)), svg = await bakeBackdrop();
    if (check) {
      let current = null;
      try { current = readFileSync(output, 'utf8'); }
      catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (current !== svg) {
        console.error(`Stale or missing: ${output}. Run node scripts/bake-client-backdrop.mjs`);
        process.exitCode = 1;
      } else console.log(`Current: ${output} (${Buffer.byteLength(svg)} bytes)`);
    } else {
      mkdirSync(dirname(output), { recursive: true });
      writeFileSync(output, svg);
      console.log(`Baked: ${output} (${Buffer.byteLength(svg)} bytes)`);
    }
  } catch (error) {
    console.error(`Client backdrop: ${error.message}`);
    process.exitCode = 1;
  }
}
